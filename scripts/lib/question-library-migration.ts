// Turns the APPROVED question library file into a migration, so it reaches live with the other migrations on go-live
// day (B-32 step 4; the seed script refuses the live database on purpose). Refuses a draft or unreviewed file through
// toSeedRows. The insert skips rows already loaded, so running it twice changes nothing. Pure.
import { toSeedRows, validateLibrary } from "@/modules/question-library";

const sql = (value: string) => `'${value.replace(/'/g, "''")}'`;
const textArray = (values: readonly string[]) => (values.length ? `array[${values.map(sql).join(", ")}]::text[]` : "'{}'::text[]");

/** The next free migration number after the highest one in the list of file names, e.g. "096". */
export function nextMigrationNumber(fileNames: readonly string[]): string {
  const numbers = fileNames.map((f) => /^(\d{3})_/.exec(f)?.[1]).filter((n): n is string => !!n).map(Number);
  return String((numbers.length ? Math.max(...numbers) : 0) + 1).padStart(3, "0");
}

/** The migration SQL for an approved library file. Throws when the file is a draft, unreviewed or invalid. */
export function libraryMigrationSql(raw: unknown, number: string, sourcePath: string): string {
  const rows = toSeedRows(raw);
  const result = validateLibrary(raw);
  if (!result.ok || !result.file.review) throw new Error("The library file is not approved by a reviewer");
  const { review, version } = result.file;
  const values = rows
    .map((r) => `  (${sql(r.industry)}, ${sql(r.template)}, ${textArray(r.tags ?? [])}, ${sql(r.intent)}, ${r.version})`)
    .join(",\n");
  return `-- Migration ${number}: question library version ${version}, ${rows.length} templates, approved by ${review.reviewer} on ${review.reviewedAt} (B-32).
-- Generated by scripts/migration-question-library.ts from ${sourcePath}; do not edit by hand. Regenerate from the
-- approved file instead. Additive (D-43): inserts rows only. A template already loaded for this version is skipped,
-- so running it twice changes nothing. question_library itself and its grants come from migrations 021 and 094.

insert into public.question_library (industry, template, tags, intent, version, active)
select v.industry, v.template, v.tags, v.intent, v.version, true
from (values
${values}
) as v(industry, template, tags, intent, version)
where not exists (
  select 1
  from public.question_library q
  where q.version = v.version and q.industry = v.industry and q.template = v.template
);
`;
}
